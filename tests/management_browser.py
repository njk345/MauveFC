"""Run against the served static demo export."""
from playwright.sync_api import sync_playwright,expect
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox']);page=b.new_page(viewport={'width':390,'height':844})
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:3000/captain/fixtures/',wait_until='networkidle')
 page.get_by_role('button',name='Add fixture',exact=True).click()
 page.get_by_role('textbox',name='Opponent',exact=True).fill('Test Visitors')
 page.get_by_label('Kickoff · New York time').fill('2026-12-10T19:00')
 page.get_by_role('textbox',name='Venue',exact=True).fill('Test field')
 page.get_by_role('button',name='Save fixture',exact=True).click()
 expect(page.get_by_role('status')).to_contain_text('Sample fixture saved')
 page.reload(wait_until='networkidle')
 expect(page.get_by_role('button').filter(has_text='Test Visitors')).to_have_count(1)
 assert page.evaluate('document.documentElement.scrollWidth')==390
 page.goto('http://127.0.0.1:3000/captain/roster/',wait_until='networkidle')
 page.get_by_role('button',name='Add player',exact=True).click()
 page.get_by_role('textbox',name='Player name',exact=True).fill('Test Newcomer')
 page.get_by_role('spinbutton',name='Shirt number',exact=True).fill('22')
 page.get_by_role('button',name='Save player',exact=True).click()
 expect(page.get_by_role('status')).to_contain_text('Sample roster saved')
 page.goto('http://127.0.0.1:3000/players/',wait_until='networkidle')
 page.get_by_role('textbox',name='Search players').fill('Test Newcomer')
 expect(page.locator('.player-card')).to_have_count(0)
 page.goto('http://127.0.0.1:3000/captain/roster/',wait_until='networkidle')
 page.get_by_role('button').filter(has_text='Test Newcomer').click()
 page.get_by_role('checkbox',name='Approve this profile for the public club site').check()
 page.get_by_role('button',name='Save player',exact=True).click()
 expect(page.get_by_role('status')).to_contain_text('Sample roster saved')
 page.goto('http://127.0.0.1:3000/players/',wait_until='networkidle')
 page.get_by_role('textbox',name='Search players').fill('Test Newcomer')
 expect(page.locator('.player-card')).to_have_count(1)
 page.locator('.player-card').click()
 expect(page.locator('h1')).to_have_text('Test Newcomer')
 page.goto('http://127.0.0.1:3000/login/',wait_until='networkidle')
 expect(page.get_by_text('Live sign-in is being connected.')).to_be_visible()
 assert page.evaluate('document.documentElement.scrollWidth')==390
 assert not errors,errors
 print('PASS fixture creation and persistence, private roster approval, new profile links, mobile layout and honest sign-in setup state')
 b.close()
